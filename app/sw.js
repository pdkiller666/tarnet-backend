const CACHE = 'tarnet-app-v34';

const ASSETS = [
  '/app/',
  '/app/index.html',
  '/app/styles.css',
  '/app/app.js',
  '/app/agents.js',
  '/app/icon.svg',
  '/app/manifest.webmanifest',
  /* Иконки из манифеста и головы: их запрашивает браузер и iOS при
   * установке. Без предзагрузки установка с иконкой ломалась бы в офлайне,
   * а тест 25.4 справедливо ловил ссылки в HTML, которых нет в кэше. */
  '/app/icon-192.png',
  '/app/icon-512.png',
  '/app/icon-180.png',
  '/app/favicon-32.png',
  /* Вендорные библиотеки входят в предзагрузку: без них офлайн-режим
   * отрисовал бы ответ как простой текст, а страница запросила бы
   * отсутствующие файлы и мигала ошибкой в консоли. */
  '/app/vendor/marked.min.js',
  '/app/vendor/highlight.min.js',
  '/app/vendor/hljs-theme.css',
  /* Ed25519 для вкладки «Агенты». Без этого файла в офлайне не посчитать
   * публичный ключ из seed, и неизвлекаемый ключ агента станет бесполезен
   * ровно тогда, когда сеть недоступна. */
  '/app/vendor/ed25519.js',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      /* Почему не add() из Cache API: он делает обычный fetch и УВАЖАЕТ
       * HTTP-кэш браузера. Ассеты /app/ отдаются с max-age, поэтому в новый
       * кэш мог лечь старый файл из HTTP-кэша — и тогда поднятая версия
       * CACHE ничего не чинит: в ней оказывается тот же старый CSS.
       * cache: 'reload' идёт в сеть мимо кэша, а cache.put кладёт свежий
       * ответ. Так «новая версия» значит действительно новые байты.
       *
       * Поштучно, а не addAll: один недоступный ассет не должен ломать
       * установку воркера целиком. */
      .then((cache) => Promise.all(
        ASSETS.map((url) => fetch(url, { cache: 'reload' })
          .then((res) => (res && res.ok ? cache.put(url, res) : null))
          .catch(() => null)),
      ))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)),
      ))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;

  /* Только GET и только своя статика. POST /inference, /health, /balance
   * и всё остальное идёт в сеть напрямую — иначе офлайн-кэш начнёт
   * отвечать за сервер. */
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (!url.pathname.startsWith('/app/')) return;

  event.respondWith(
    caches.match(req).then((hit) => {
      /* stale-while-revalidate: свежий ответ забираем В ФОНЕ и обновляем
       * кэш, но не заставляем человека ждать сеть. Отдать из кэша и
       * промолчать было бы прежним багом: файл обновится на сервере, а
       * клиент продолжит крутить старую копию месяцами.
       *
       * fetch идёт с cache:'reload' — иначе HTTP-кэш браузера вернул бы
       * тот же старый файл, и ревалидация была бы фиктивной. */
      const refresh = fetch(req, { cache: 'reload' })
        .then((res) => {
          if (res && res.ok) {
            const copy = res.clone();
            caches.open(CACHE)
              .then((cache) => cache.put(req, copy))
              .catch(() => {});
          }
          return res;
        })
        .catch(() => null);

      if (hit) {
        /* Фон обновляется, ответ отдаётся сразу. */
        event.waitUntil(refresh);
        return hit;
      }
      return refresh.then((res) => res || caches.match('/app/index.html'));
    }),
  );
});
